// In-Memory Storage implementation: avoids browser disk storage, cookies, and local storage
class MemoryStorage implements Storage {
  private store: Record<string, string> = {};

  get length(): number {
    return Object.keys(this.store).length;
  }

  clear(): void {
    this.store = {};
  }

  getItem(key: string): string | null {
    return this.store[key] ?? null;
  }

  key(index: number): string | null {
    return Object.keys(this.store)[index] ?? null;
  }

  removeItem(key: string): void {
    delete this.store[key];
  }

  setItem(key: string, value: string): void {
    this.store[key] = String(value);
  }
}

// Strictly initialize pure in-memory stores to eliminate browser storage and cookies
export const safeStorage: Storage = new MemoryStorage();
export const safeSessionStorage: Storage = new MemoryStorage();
